| Russian subtitles for the intro newsreel (DATA_D1, sub CPU).
|
| DATA_D1's per-frame routine (header long $28008) is redirected to `tick`,
| which runs the subtitle player and then jumps to the original routine.
| The player walks CUES (generated by introsubs.py) against the CD-DA track
| time in $787a - the same BCD clock (MM SS FF 00) that DATA_D1's own scene
| table uses - so the text follows the narration exactly.
|
| A cue is drawn at run time: glyphs from GLYPHS into a 1-bpp line buffer,
| a 1-px outline around them, then 4-bpp sprite tiles in Word RAM ($BC000,
| free during the intro), queued for VRAM $C800 and $F000 (free in every
| scene)
| through the engine's DMA queue ($e322). The text shows as engine object
| 1 (listed first, so it wins the per-line sprite limit): 4x2-tile sprites. The colours are two entries
| of palette line 0 that are white and black in the scene at that time
| (picked offline per cue); the text fades with the picture.

        .equ    OBJ,     0x7a50         | object 1: $7a00 + $50 (scenes use 5-$20)
        .equ    TIME,    0x787a         | CD-DA track time, BCD
        .equ    STEP,    0x7896         | DATA_D1 scene step (>0 once the track runs)
        .equ    QUEUE,   0xb6000        | DMA queue, first word 0 = idle
        .equ    WBUF,    0xbc000        | Word RAM, sub view
        .equ    WMAIN,   0x23c000       | the same, main view
        .equ    VDEST,   0xc800         | VRAM for line 1 (tile $640)
        .equ    VDEST1,  0xf000         | VRAM for line 2 (tile $780)
        .equ    TILE0,   0x640
        .equ    TILE1,   0x780
        .equ    SCR,     0x4e000        | scratch PRG-RAM (free while DATA_D1 runs)
        .equ    CBUF,    SCR            | 16 rows x 32 bytes: glyph pixels
        .equ    OBUF,    SCR+0x200      | the outline
        .equ    TW,      SCR+0x400      | 256 longs: byte -> 8 nibbles of the text colour
        .equ    TB,      SCR+0x800      | ... of the outline colour
        .equ    FRAME,   SCR+0xc00      | sprite table: offset word + one frame
        .equ    STREAM,  SCR+0xd00      | scene command 2 creating the object
        .equ    ORIG,    0x29266        | DATA_D1's own per-frame routine

        .text
        .globl  tick
tick:   movem.l d0-d7/a0-a6,-(sp)
        bsr.w   player
        movem.l (sp)+,d0-d7/a0-a6
        jmp     ORIG

player: lea     vars(pc),a4
        tst.w   STEP.w
        ble.w   9f
        cmp.w   #1,2(a4)                | state 1: tiles queued
        bne.s   1f
        tst.w   QUEUE                   | wait until the DMA queue drains
        bne.w   9f
        bsr.w   mkobj
        lea     vars(pc),a4             | the engine's command loop uses a4
        move.w  #2,2(a4)
        bra.s   2f
1:      cmp.w   #2,2(a4)                | state 2: shown
        bne.s   2f
        lea     OBJ,a0
        tst.w   (a0)                    | a scene change clears all objects
        bne.s   2f
        bsr.w   mkobj
        lea     vars(pc),a4
2:      move.w  (a4),d0                 | next cue
        mulu    #10,d0
        lea     CUES(pc),a3
        add.w   d0,a3
        move.l  (a3),d1
        cmp.l   #-1,d1
        beq.s   9f
        cmp.l   TIME.w,d1
        bhi.s   9f
        tst.w   QUEUE                   | our tiles must not interleave a load
        bne.s   9f
        addq.w  #1,(a4)
        lea     OBJ,a0
        jsr     0xeea0                  | remove the old text
        clr.w   2(a4)
        move.l  4(a3),d0
        beq.s   9f                      | a hide cue
        move.l  d0,a0
        move.w  8(a3),d7
        move.w  d7,4(a4)                | palette for mkobj
        bsr.w   render
        moveq   #2,d6
        move.l  #WMAIN,a5
        move.l  #VDEST,a6
        move.w  #0x800,d7
        jsr     0xe322
        moveq   #2,d6
        move.l  #WMAIN+0x800,a5
        move.l  #VDEST1,a6
        move.w  #0x800,d7
        jsr     0xe322
        move.w  #1,2(a4)
9:      rts

| Create object 1 showing FRAME (built by render).
mkobj:  lea     STREAM,a0
        move.l  #0x020c0101,(a0)+       | command 2, 12 bytes, id 1, flags 1 (still)
        clr.l   (a0)+                   | x, y
        move.l  #FRAME,(a0)+
        lea     script(pc),a1
        move.l  a1,d0
        sub.l   a0,d0
        subq.l  #2,d0
        move.w  d0,(a0)+
        move.b  #0xff,(a0)
        lea     STREAM,a5
        jmp     0xf6a6

| a0 = text: per line x (byte) then glyph bytes, $FE between lines, $FF at the end.
| d7 = colours: line << 8 | text << 4 | outline.
render: move.w  d7,d0                   | colour tables
        lsr.w   #4,d0
        and.l   #15,d0
        move.w  d7,d1
        and.l   #15,d1
        lea     TW,a1
        lea     TB,a2
        moveq   #0,d2                   | byte value
3:      moveq   #0,d3
        moveq   #0,d4
        moveq   #7,d5
4:      lsl.l   #4,d3
        lsl.l   #4,d4
        btst    d5,d2
        beq.s   5f
        or.b    d0,d3
        or.b    d1,d4
5:      dbra    d5,4b
        move.l  d3,(a1)+
        move.l  d4,(a2)+
        addq.w  #1,d2
        cmp.w   #256,d2
        bne.s   3b
        lea     WBUF,a1                 | blank all 128 tiles
        move.w  #1023,d0
6:      clr.l   (a1)+
        dbra    d0,6b
        lea     FRAME+4,a5              | sprite entries
        moveq   #0,d6                   | sprite count
        moveq   #0,d5                   | line number
        move.l  a0,a2
        moveq   #1,d4
7:      move.b  (a2)+,d0
        cmp.b   #0xff,d0
        beq.s   8f
        cmp.b   #0xfe,d0
        bne.s   7b
        addq.w  #1,d4
        bra.s   7b
8:      lsl.w   #4,d4
        move.w  #216,d3
        sub.w   d4,d3                   | top of the first line
        move.w  d3,vars+6
line:   lea     CBUF,a1
        moveq   #127,d0
10:     clr.l   (a1)+
        dbra    d0,10b
        moveq   #0,d4
        move.b  (a0)+,d4                | x of the line (outline margin included)
        move.w  d4,d3
        lsr.w   #5,d3
        move.w  d3,vars+8               | first sprite column
11:     moveq   #0,d0
        move.b  (a0)+,d0
        cmp.b   #0xfe,d0
        bcc.s   13f
        mulu    #14,d0
        lea     GLYPHS(pc),a1
        add.w   d0,a1
        moveq   #0,d2
        move.b  (a1)+,d2                | advance
        lea     CBUF+32,a2
        move.w  d4,d0
        lsr.w   #3,d0
        add.w   d0,a2
        move.w  d4,d1
        and.w   #7,d1
        moveq   #12,d3
12:     moveq   #0,d0
        move.b  (a1)+,d0
        lsl.w   #8,d0
        lsr.w   d1,d0
        or.b    d0,1(a2)
        lsr.w   #8,d0
        or.b    d0,(a2)
        lea     32(a2),a2
        dbra    d3,12b
        add.w   d2,d4
        bra.s   11b
13:     move.b  d0,vars+10              | $FE or $FF
        add.w   #2,d4                   | last sprite column
        lsr.w   #5,d4
        move.w  d4,vars+12
        bsr.w   outline
        bsr.w   tiles
        cmp.b   #0xff,vars+10
        beq.s   14f
        addq.w  #1,d5
        bra.w   line
14:     lea     FRAME,a1
        move.w  #2,(a1)+
        subq.w  #1,d6
        move.w  d6,(a1)
        rts

| OBUF = 4-neighbourhood of CBUF minus CBUF.
outline:
        lea     CBUF,a1
        lea     OBUF,a2
        moveq   #0,d0                   | row
15:     moveq   #0,d1                   | byte
16:     move.w  d0,d2
        lsl.w   #5,d2
        add.w   d1,d2                   | index
        moveq   #0,d3
        move.b  (a1,d2.w),d3            | c
        move.b  d3,d4
        add.b   d4,d4                   | c << 1
        cmp.w   #31,d1
        beq.s   17f
        move.b  1(a1,d2.w),d7
        lsr.b   #7,d7
        or.b    d7,d4
17:     move.b  d3,d7
        lsr.b   #1,d7
        or.b    d7,d4                   | | c >> 1
        tst.w   d1
        beq.s   18f
        move.b  -1(a1,d2.w),d7
        lsl.b   #7,d7
        or.b    d7,d4
18:     tst.w   d0
        beq.s   19f
        or.b    -32(a1,d2.w),d4
19:     cmp.w   #15,d0
        beq.s   20f
        or.b    32(a1,d2.w),d4
20:     not.b   d3
        and.b   d3,d4
        move.b  d4,(a2,d2.w)
        addq.w  #1,d1
        cmp.w   #32,d1
        bne.s   16b
        addq.w  #1,d0
        cmp.w   #16,d0
        bne.s   15b
        rts

| Tiles of line d5 for sprite columns vars+8 .. vars+12, and their sprites.
tiles:  move.w  vars+8,d0               | sprite column
21:     cmp.w   vars+12,d0
        bhi.w   25f
        cmp.w   #8,d0
        bcc.w   25f
        move.w  d5,d1                   | tile index: line*64 + col*8
        lsl.w   #6,d1
        move.w  d0,d2
        lsl.w   #3,d2
        add.w   d2,d1
        move.w  d0,d2                   | VRAM tile: line 0 at $640, line 1 at $780
        lsl.w   #3,d2
        add.w   #TILE0,d2
        tst.w   d5
        beq.s   26f
        add.w   #TILE1-TILE0,d2
26:                                     | sprite: y, size, attr, x
        move.w  vars+6,d3
        move.w  d5,d4
        lsl.w   #4,d4
        add.w   d4,d3
        move.w  d3,(a5)+
        move.w  #0x0d00,(a5)+
        move.w  vars+4,d3
        lsr.w   #8,d3
        and.w   #3,d3
        ror.w   #3,d3
        or.w    #0x8000,d3
        add.w   d2,d3
        move.w  d3,(a5)+
        move.w  d0,d3
        lsl.w   #5,d3
        move.w  d3,(a5)+
        addq.w  #1,d6
        lea     WBUF,a1                 | tile data: 4 columns x 2 rows
        lsl.w   #5,d1
        add.w   d1,a1
        moveq   #0,d4                   | tile column 0..3
22:     moveq   #0,d7                   | row 0..15
23:     move.w  d7,d2
        lsl.w   #5,d2
        move.w  d0,d3
        lsl.w   #2,d3
        add.w   d4,d3
        add.w   d3,d2                   | byte index in the row buffers
        lea     CBUF,a2
        moveq   #0,d3
        move.b  (a2,d2.w),d3
        add.w   d3,d3
        add.w   d3,d3
        lea     TW,a2
        move.l  (a2,d3.w),d1
        lea     OBUF,a2
        moveq   #0,d3
        move.b  (a2,d2.w),d3
        add.w   d3,d3
        add.w   d3,d3
        lea     TB,a2
        or.l    (a2,d3.w),d1
        move.l  d1,(a1)+
        addq.w  #1,d7
        cmp.w   #16,d7
        bne.s   23b
        addq.w  #1,d4
        cmp.w   #4,d4
        bne.s   22b
        addq.w  #1,d0
        bra.w   21b
25:     rts

        .even
| index, state, colours, y top, first column, line end, last column
vars:   .word   0, 0, 0, 0, 0, 0, 0, 0
script: .byte   0, 0, 0x7f, 0xff, 0x81, 0, 0, 0

        .include "introsubs_data.s"
