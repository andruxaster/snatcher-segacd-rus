"""Generate tools/actfont.py: Cyrillic capitals and digits for the act titles
(ACT 1 SNATCH...) - heavy condensed italic, 21 px capitals.

Needs Liberation Sans Bold (fonts-liberation); the result is committed, so
the build does not need it.
    python tools/gen_actfont.py [path/to/LiberationSans-Bold.ttf]
"""
import os, sys
import numpy as np
from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"
CHARS = "АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ0123456789"
CAP, SS, XSCALE, SHEAR = 21, 8, 0.66, 0.22


def glyph(ch, font):
    W = 60 * SS
    im = Image.new("L", (W, 40 * SS), 0)
    ImageDraw.Draw(im).text((8 * SS, 0), ch, font=font, fill=255)
    a = np.array(im) > 127
    rows = np.nonzero(a.any(1))[0]
    # cap height from "Н"
    return a


def main():
    ref = ImageFont.truetype(TTF, 100)
    a = np.array((lambda im: (ImageDraw.Draw(im).text((0, 0), "Н", font=ref, fill=255), im)[1])(Image.new("L", (200, 200))))
    rows = np.nonzero(a.any(1))[0]
    size = int(100 * CAP * SS / (rows[-1] - rows[0] + 1))
    font = ImageFont.truetype(TTF, size)
    top = None
    out = {}
    for ch in CHARS:
        im = Image.new("L", (40 * SS, 40 * SS), 0)
        ImageDraw.Draw(im).text((6 * SS, 0), ch, font=font, fill=255)
        if top is None:
            hn = Image.new("L", (40 * SS, 40 * SS), 0)
            ImageDraw.Draw(hn).text((6 * SS, 0), "Н", font=font, fill=255)
            top = int(np.nonzero(np.array(hn).any(1))[0][0])
        im = im.crop((0, top - SS, im.width, top + (CAP + 2) * SS))
        im = im.transform(im.size, Image.AFFINE, (1, SHEAR, -SHEAR * im.height, 0, 1, 0), Image.BILINEAR)
        im = im.resize((int(im.width * XSCALE / SS), CAP + 2), Image.BOX)
        b = np.array(im) > 110
        cols = np.nonzero(b.any(0))[0]
        b = b[:, cols[0]:cols[-1] + 1]
        out[ch] = ["".join("#" if v else "." for v in r) for r in b]
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "actfont.py"), "w") as f:
        f.write('"""Act title capitals (generated by tools/gen_actfont.py from Liberation Sans Bold:\n'
                'condensed, slanted). Rows: 1 px above the capitals, 21 px capitals, 1 px below."""\n\nG = {\n')
        for ch, rows in out.items():
            f.write(f" {ch!r}: [\n" + "".join(f"  {r!r},\n" for r in rows) + " ],\n")
        f.write("}\n")


if __name__ == "__main__":
    main()
