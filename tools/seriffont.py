for k, v in G.items():
    assert len(v) == 9 and len({len(r) for r in v}) == 1, k

SPACE, GAP = 10, 3


def width(text):
    return sum(SPACE if c == " " else len(G[c][0]) + GAP for c in text) - GAP


def render(img, x, y, text, core, aa, outline):
    """`y` is the top of the outline box (core starts at y + 1)."""
    for ch in text:
        if ch == " ":
            x += SPACE
            continue
        g = G[ch]
        w = len(g[0])
        c = np.array([[p == "#" for p in r] for r in g])
        a = np.array([[p == "o" for p in r] for r in g])
        b = np.zeros((11, w + 2), dtype=bool)
        b[1:10, 1:w + 1] = c | a
        o = np.zeros_like(b)
        o[1:, :] |= b[:-1, :]; o[:-1, :] |= b[1:, :]
        o[:, 1:] |= b[:, :-1]; o[:, :-1] |= b[:, 1:]
        o &= ~b
        reg = img[y:y + 11, x - 1:x + w + 1]
        reg[o] = outline
        reg[1:10, 1:w + 1][c] = core
        reg[1:10, 1:w + 1][a] = aa
        x += w + GAP
    return x


def wrap(text, px):
    lines, cur = [], ""
    for word in text.split(" "):
        t = word if not cur else cur + " " + word
        if width(t) <= px:
            cur = t
        else:
            lines.append(cur)
            cur = word
    return lines + [cur]
