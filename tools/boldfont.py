for k, v in G.items():
    v += ["." * len(v[0])] * (8 - len(v))
    assert len(v) == 8 and len({len(r) for r in v}) == 1, k


def base(ch):
    return np.array([[c == "#" for c in r] for r in G[ch]], dtype=bool)


def width(text):
    return sum(base(c).shape[1] + 3 for c in text) - 1


def render(img, x, y, text, ink, shadow, bg=None):
    """Draw `text` into the colour-index image at (x, y) (top of the cell)."""
    for ch in text:
        b = base(ch)
        h, w = b.shape
        m = np.zeros((h, w + 2), dtype=bool)
        m[:, :w] = b
        ink_m = m.copy()
        ink_m[:, 1:] |= m[:, :-1]
        sh = np.zeros_like(ink_m)
        sh[:, 1:] = ink_m[:, :-1] & ~ink_m[:, 1:]
        reg = img[y:y + h, x:x + w + 2]
        reg[sh[:, :reg.shape[1]]] = shadow
        reg[ink_m[:, :reg.shape[1]]] = ink
        x += w + 3
    return x


def wrap(text, px):
    """Greedy wrap; a one-letter word (в, и, с, а...) stays with the next one."""
    words, out = text.split(" "), []
    for w in words:
        if out and len(out[-1].split(" ")[-1]) == 1 and out[-1][-1].isalpha():
            out[-1] += " " + w
        else:
            out.append(w)
    lines, cur = [], ""
    for word in out:
        t = word if not cur else cur + " " + word
        if width(t) <= px:
            cur = t
        else:
            lines.append(cur)
            cur = word
    return lines + [cur]
