def build(font, widths):
    """(glyph bytes for codes FIRST..LAST, width bytes) from the game's own
    Latin font (`font`: 8 bytes per glyph from 0x20, `widths`: one per glyph)."""
    gl, wd = bytearray(), bytearray()
    by_code = {v: k for k, v in CODES.items()}
    for code in range(FIRST, LAST + 1):
        ch = by_code[code]
        if ch in LATIN:
            i = ord(LATIN[ch]) - 0x20
            gl += font[i * 8:i * 8 + 8]
            wd.append(widths[i])
            continue
        rows = G[ch]
        assert len(rows) == 8 and all(len(r) == 8 for r in rows), ch
        gl += bytes(int(r.replace("#", "1").replace(".", "0"), 2) for r in rows)
        right = max((r.rfind("#") for r in rows), default=0)
        wd.append(right + 2)
    return bytes(gl), bytes(wd)


def encode(text):
    """Russian/ASCII text -> game bytes (line break: ￥ or \\n -> 0xF2)."""
    out = bytearray()
    for ch in text:
        if ch in CODES:
            out.append(CODES[ch])
        elif ch in "￥\n":
            out.append(0xF2)
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ord(ch))
        else:
            raise ValueError(f"no glyph for {ch!r}")
    return bytes(out)
